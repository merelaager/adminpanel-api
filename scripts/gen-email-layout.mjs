import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import mjml2html from "mjml";

const SENTINEL = "@@BODY@@";

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, "..", "src");
// Source is hand-authored; output goes under src/generated (gitignored),
// alongside the other generated code (Prisma client).
const mjmlPath = join(srcDir, "services", "email-layout.mjml");
const outDir = join(srcDir, "generated");
const outPath = join(outDir, "email-layout.ts");

const source = await readFile(mjmlPath, "utf8");
const { html, errors } = await mjml2html(source, {
  filePath: mjmlPath,
  validationLevel: "strict",
});

if (errors.length > 0) {
  console.error("MJML compilation errors:");
  for (const err of errors) console.error(`  ${err.formattedMessage ?? err}`);
  process.exit(1);
}

const markerCount = html.split(SENTINEL).length - 1;
if (markerCount !== 1) {
  console.error(
    `Expected exactly one "${SENTINEL}" marker in the compiled output, found ${markerCount}.`,
  );
  process.exit(1);
}

const [pre, post] = html.split(SENTINEL);

const file = `// AUTO-GENERATED by scripts/gen-email-layout.mjs from src/services/email-layout.mjml.
// Do not edit by hand; edit email-layout.mjml and run \`yarn gen:email\`.

export const getEmailRegistrationBodyPre = (): string =>
  ${JSON.stringify(pre)};

export const getEmailRegistrationBodyPost = (): string =>
  ${JSON.stringify(post)};
`;

await mkdir(outDir, { recursive: true });
await writeFile(outPath, file);
console.log(`Wrote ${outPath}`);
